// PhiOrbit O2: exact 3D position permutations and independent observer frame.
import { createHash } from 'node:crypto';

const N = 27;
const MAX_OPS = 4096;
const must = (ok, message) => { if (!ok) throw new Error(message); };
const int = (v, lo, hi) => Number.isInteger(v) && v >= lo && v <= hi;
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const identity = () => Array.from({ length: N }, (_, i) => i);
const key = p => p.join(',');
const axes = ['x', 'y', 'z'];

export function position(x, y, z) {
  must([x, y, z].every(v => int(v, 0, 2)), 'invalid coordinates');
  return x + 3 * y + 9 * z;
}
export function coordinates(id) {
  must(int(id, 0, 26), 'invalid position');
  return [id % 3, Math.floor(id / 3) % 3, Math.floor(id / 9)];
}

function validatePermutation(p) {
  must(Array.isArray(p) && p.length === N &&
    Array.from(p).every(v => int(v, 0, 26)) && new Set(p).size === N, 'invalid permutation');
}
export function composePermutation(after, before) {
  validatePermutation(after); validatePermutation(before);
  return before.map(i => after[i]);
}
export function inversePermutation(p) {
  validatePermutation(p);
  const inverse = identity();
  for (const [i, j] of p.entries()) inverse[j] = i;
  return inverse;
}

// Active right-handed +90 degree rotation around a centered coordinate axis.
// A permutation maps source position to destination position.
export function rotation(axis, turns, layer = null) {
  must(axes.includes(axis) && int(turns, 1, 3), 'invalid rotation');
  must(layer === null || int(layer, 0, 2), 'invalid layer');
  const index = axes.indexOf(axis);
  return identity().map(id => {
    let [x, y, z] = coordinates(id);
    if (layer !== null && [x, y, z][index] !== layer) return id;
    for (let t = 0; t < turns; t++) {
      if (axis === 'x') [y, z] = [2 - z, y];
      else if (axis === 'y') [x, z] = [z, 2 - x];
      else [x, y] = [2 - y, x];
    }
    return position(x, y, z);
  });
}

// Stable enumeration of the 24 proper rigid orientations, generated by BFS.
const frames = [identity()];
const frameKeys = new Map([[key(frames[0]), 0]]);
for (let i = 0; i < frames.length; i++) for (const axis of axes) {
  const p = composePermutation(rotation(axis, 1), frames[i]);
  if (!frameKeys.has(key(p))) {
    frameKeys.set(key(p), frames.length); frames.push(p);
  }
}
must(frames.length === 24, 'unexpected rigid group size');

export function rigidFrames() { return frames.map(p => [...p]); }
export function frameCompose(after, before) {
  must(int(after, 0, 23) && int(before, 0, 23), 'invalid frame');
  return frameKeys.get(key(composePermutation(frames[after], frames[before])));
}

// Virtual nested addresses use base-27 digits; no nested payload is allocated.
export function nestedAddress(path) {
  must(Array.isArray(path) && path.length <= 64 &&
    Array.from(path).every(v => int(v, 0, 26)), 'invalid nested path');
  return path.reduce((id, slot) => 27n * id + 1n + BigInt(slot), 0n);
}
export function transformPath(path, frame) {
  nestedAddress(path);
  must(int(frame, 0, 23), 'invalid frame');
  // Same observer frame at each level. This does not relocate stored children.
  return path.map(slot => frames[frame][slot]);
}

// Canonical QC2 snapshot: ASCII QC2, frame ID, 27 unique position labels.
// The label is an abstract token, not a Rubik's cubie with sticker orientation.
export function initialCube() {
  return Buffer.from([81, 67, 50, 0, ...identity()]);
}
export function decodeCube(snapshot) {
  must(Buffer.isBuffer(snapshot) && snapshot.length === 31 &&
    snapshot.subarray(0, 3).equals(Buffer.from('QC2')) && int(snapshot[3], 0, 23),
    'invalid QC2 envelope');
  const labels = [...snapshot.subarray(4)];
  validatePermutation(labels);
  return { frame: snapshot[3], labels };
}
export function observeCube(snapshot, viewPosition) {
  const { frame, labels } = decodeCube(snapshot);
  must(int(viewPosition, 0, 26), 'invalid view position');
  return labels[inversePermutation(frames[frame])[viewPosition]];
}
function parse(op) {
  must(op && typeof op === 'object' && !Array.isArray(op) &&
    ['frame', 'whole', 'layer'].includes(op.kind), 'invalid operation');
  const { kind, axis, turns } = op;
  const layer = kind === 'layer' ? op.layer : null;
  must(kind === 'layer' ? int(layer, 0, 2) : !Object.hasOwn(op, 'layer'), 'invalid layer scope');
  rotation(axis, turns, layer);
  return kind === 'layer' ? { kind, axis, turns, layer } : { kind, axis, turns };
}

export function executeCube(snapshot, operations, fuel) {
  must(int(fuel, 0, MAX_OPS) && Array.isArray(operations) && operations.length <= fuel,
    'invalid fuel or program');
  let { frame, labels } = decodeCube(snapshot);
  const program = Array.from(operations, parse);
  const undo = [], steps = [];
  for (const op of program) {
    const p = rotation(op.axis, op.turns, op.kind === 'layer' ? op.layer : null);
    const previous = frame;
    if (op.kind === 'frame') frame = frameCompose(frameKeys.get(key(p)), frame);
    else {
      const next = identity();
      for (let i = 0; i < N; i++) next[p[i]] = labels[i];
      labels = next;
    }
    steps.push({ ...op, frame_before: previous, frame_after: frame,
      moved_positions: op.kind === 'frame' ? 0 : p.filter((v, i) => v !== i).length });
    undo.push({ ...op, turns: 4 - op.turns });
  }
  const output = Buffer.from([81, 67, 50, frame, ...labels]);
  const receipt = { schema: 'phiorbit/o2', evidence: 'SIMULATED', authority: 'NONE',
    input_sha256: sha(snapshot), output_sha256: sha(output), used: program.length,
    remaining: fuel - program.length, steps, inverse_program: undo.reverse() };
  receipt.receipt_sha256 = sha(JSON.stringify(receipt));
  return { output, receipt };
}
export function verifyCube(snapshot, operations, fuel, output, receipt) {
  try {
    const expected = executeCube(snapshot, operations, fuel);
    return Buffer.isBuffer(output) && output.equals(expected.output) &&
      JSON.stringify(receipt) === JSON.stringify(expected.receipt);
  } catch { return false; }
}

// Physical footprint for a future O1 compiler; frame edits conflict with
// frame observations, not with physical-coordinate writes in this model.
export function footprint(operation) {
  const op = parse(operation);
  if (op.kind === 'frame') return { frame: true, positions: [] };
  const index = axes.indexOf(op.axis);
  return { frame: false, positions: identity().filter(i =>
    op.kind === 'whole' || coordinates(i)[index] === op.layer) };
}

export function studyCube() {
  const input = initialCube();
  const a = { kind: 'layer', axis: 'x', layer: 0, turns: 1 };
  const b = { kind: 'layer', axis: 'y', layer: 0, turns: 1 };
  const forward = executeCube(input, [a, b], 2);
  const reverse = executeCube(input, [b, a], 2);
  const restored = executeCube(forward.output, forward.receipt.inverse_program, 2);
  return { schema: 'phiorbit/o2-study', evidence: 'SIMULATED', authority: 'NONE',
    proper_rigid_frames: frames.length, positions: N,
    noncommuting_layer_example: !forward.output.equals(reverse.output),
    differing_positions: [...forward.output.subarray(4)].filter((v, i) => v !== reverse.output[i + 4]).length,
    exact_inverse: restored.output.equals(input), forward: forward.receipt };
}
